                }
            }

            for (int i = 0; i < simpleReportDefinitionsCount; i++)
            { 
                ReportCollection result = ReportsBeingGenerated[i].BuildReport(fullPrecision);
                reportCollection.Add(result);
            }

            return reportCollection;
        }

